// The README's Supported OpenCode version table, generated from the release tags: each `vX.Y.Z` tag's
// package.json names the OpenCode V2 version it is pinned to. Prereleases are left out.
//   bun script/compat-table.ts           # rewrite the table in README.md
//   bun script/compat-table.ts --check   # fail if README.md's table is not the generated one
import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"

export type Release = { version: string; pin: string; beta: boolean }

export const START = "<!-- compat-table:start: generated by script/compat-table.ts from the release tags -->"
export const END = "<!-- compat-table:end -->"
const HEADER = ["| opencode-courier | OpenCode V2 (`opencode` and `@opencode/plugin`) |", "|---|---|"]
const BETA_NOTE = " (the beta line: `opencode2` from `@opencode-ai/cli`, and `@opencode-ai/plugin`)"

const prerelease = (version: string) => version.includes("-")

/** What a package.json pins, or undefined for one that names no plugin API. */
export function releaseOf(manifest: { version?: string; peerDependencies?: Record<string, string> }): Release | undefined {
  const peers = manifest.peerDependencies ?? {}
  const pin = peers["@opencode/plugin"] ?? peers["@opencode-ai/plugin"]
  if (!manifest.version || !pin) return undefined
  return { version: manifest.version, pin, beta: peers["@opencode/plugin"] === undefined }
}

/** The table's lines, newest first; consecutive releases on one pin share a row, oldest first in it. */
export function table(releases: readonly Release[]): string[] {
  const sorted = releases.filter((release) => !prerelease(release.version)).toSorted((a, b) => Bun.semver.order(b.version, a.version))
  const rows: Release[][] = []
  for (const release of sorted) {
    const last = rows.at(-1)
    if (last && last[0]!.pin === release.pin && last[0]!.beta === release.beta) last.unshift(release)
    else rows.push([release])
  }
  return [
    ...HEADER,
    ...rows.map((row) => `| ${row.map((release) => release.version).join(", ")} | ${row[0]!.pin}${row[0]!.beta ? BETA_NOTE : ""} |`),
  ]
}

/** `readme` with the lines between the markers replaced by `lines`. */
export function replaceTable(readme: string, lines: readonly string[]): string {
  const start = readme.indexOf(START)
  const end = readme.indexOf(END)
  if (start < 0 || end < start) throw new Error(`README.md has no ${START} ... ${END} block`)
  return `${readme.slice(0, start + START.length)}\n${lines.join("\n")}\n${readme.slice(end)}`
}

function git(...args: string[]): string {
  return execFileSync("git", args, { encoding: "utf8" })
}

/** Every release tag's pin, and package.json's version too while it has no tag (a release branch). */
export function releasesFromGit(): Release[] {
  const tags = git("tag", "--list", "v*").split("\n").filter((tag) => /^v\d+\.\d+\.\d+$/.test(tag))
  if (tags.length === 0) throw new Error("no release tags: fetch them with `git fetch --tags` (CI: fetch-depth: 0)")
  const releases = tags.flatMap((tag) => releaseOf(JSON.parse(git("show", `${tag}:package.json`))) ?? [])
  const current = releaseOf(JSON.parse(readFileSync("package.json", "utf8")))
  if (current && !prerelease(current.version) && !tags.includes(`v${current.version}`)) releases.push(current)
  return releases
}

if (import.meta.main) {
  const readme = readFileSync("README.md", "utf8")
  const generated = replaceTable(readme, table(releasesFromGit()))
  if (process.argv.includes("--check")) {
    if (generated !== readme) {
      console.error("README.md's Supported OpenCode version table is not the one the release tags give. Run: bun script/compat-table.ts")
      process.exit(1)
    }
  } else writeFileSync("README.md", generated)
}
